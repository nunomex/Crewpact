// Camada de i18n da app.
// - `tx(campo, lang)` resolve campos bilingues nos dados: {pt,en} | {pt:[],en:[]}
//   | string | string[]. Tolera strings soltas (migração progressiva).
// - `t(chave, lang)` devolve strings de UI a partir de STRINGS.

export const tx = (field, lang) => {
  if (field == null) return field;
  if (typeof field === 'string' || Array.isArray(field)) return field;
  return field[lang] ?? field.pt ?? field.en ?? '';
};

export const t = (key, lang = 'pt') => {
  const table = STRINGS[lang] || STRINGS.pt;
  return table[key] ?? STRINGS.pt[key] ?? key;
};

