// Constrói o modelo estruturado a partir dos stores `duties` (tabela duties) e
// `dayLog` (store FTL, para os acumulados 210). Cada dia é recalculado pelo motor
// (PSV/serviço/repouso) — fonte única de verdade.
export const buildRecordModel = ({
  duties = {}, dayLog = {}, name = '', crewId = '', operator = '', email = '', generatedAt = null,
} = {}) => {
  // Uma linha por PERÍODO DE SERVIÇO (não por dia): a EASA conta serviços (ORO.FTL.245/210),
  // por isso um dia com 2 serviços rende 2 linhas. Serviços do dia = primária + `extra`,
  // ordenados pelo report; cada um recalculado pelo motor (fonte única de verdade).
  const svcRow = (date, d, idx, nSvc) => {
    const r = computeDuty({ state: 'acc', report: d.report_time, end: d.block_on, sectors: d.sectors || 0, inBase: true });
    return {
      date: nSvc > 1 ? `${date} (${idx + 1}/${nSvc})` : date,
      report: d.report_time || '—', off: d.block_off || '—', on: d.block_on || '—',
      sectors: d.sectors || 0, flightMin: d.flight_minutes || 0,
      fdp: r.fdp.actualFdpStr || '—',
      duty: r.dutyPeriodStr || r.fdp.actualFdpStr || '—',
      rest: r.rest.restStr || (r.rest.restMin != null ? minToHhmm(r.rest.restMin) : '—'),
      over: !!r.fdp.over,
    };
  };
  const rows = Object.entries(duties)
    .filter(([, d]) => d && !d.deleted)
    .sort((a, b) => (a[0] < b[0] ? -1 : 1))
    .flatMap(([date, d]) => {
      const services = [d, ...(Array.isArray(d.extra) ? d.extra : [])]
        .filter((sv) => sv && sv.report_time && sv.block_on)
        .sort((a, b) => String(a.report_time).localeCompare(String(b.report_time)));
      return services.map((sv, idx) => svcRow(date, sv, idx, services.length));
    });

  const totalFlightMin = rows.reduce((s, r) => s + r.flightMin, 0);
  const totalSectors = rows.reduce((s, r) => s + r.sectors, 0);
  const periodStart = rows.length ? rows[0].date : null;
  const periodEnd = rows.length ? rows[rows.length - 1].date : null;
  const ref = periodEnd ? new Date(periodEnd + 'T12:00:00') : new Date();

  return {
    header: { operator, name, crewId, email, periodStart, periodEnd, generatedAt, count: rows.length },
    rows,
    totals: { flightMin: totalFlightMin, sectors: totalSectors, duties: rows.length },
    cumulative: { duty: computeDutyTime(dayLog, ref), flight: computeFlightTime(dayLog, ref) },
  };
};

// Fantasma do período no cabeçalho ("JUL ’26" · "2026" · "’25–’26") — meses FIXOS (Intl varia).
const MON3 = {
  pt: ['JAN', 'FEV', 'MAR', 'ABR', 'MAI', 'JUN', 'JUL', 'AGO', 'SET', 'OUT', 'NOV', 'DEZ'],
  en: ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'],
};
const WD3 = {
  pt: ['DOM', 'SEG', 'TER', 'QUA', 'QUI', 'SEX', 'SÁB'],
  en: ['SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'],
};
// Data da linha HUMANIZADA ("SEG 15 JUN", como a app fala) — o ISO cru era frio e ilegível
// (crítica do user ao 1.º PDF, 2026-07-10). O sufixo (1/2) dos dias com 2 serviços mantém-se.
const fmtRowDate = (dateStr, lang) => {
  const s = String(dateStr || '');
  const iso = s.slice(0, 10);
  const sfx = s.length > 10 ? s.slice(10).trim() : '';
  const d = new Date(`${iso}T12:00:00`);
  if (isNaN(d)) return { main: s, sfx: '' };
  const W = WD3[lang] || WD3.pt, M = MON3[lang] || MON3.pt;
  return { main: `${W[d.getDay()]} ${d.getDate()} ${M[d.getMonth()]}`, sfx };
};
const periodGhost = (startIso, endIso, lang) => {
  const a = String(startIso || '').slice(0, 10), b = String(endIso || '').slice(0, 10);
  if (!a) return '—';
  const M = MON3[lang] || MON3.pt;
  const [ya, ma] = [a.slice(0, 4), Number(a.slice(5, 7)) - 1];
  const [yb, mb] = [b.slice(0, 4), Number(b.slice(5, 7)) - 1];
  if (ya === yb && ma === mb) return `${M[ma]} ’${ya.slice(2)}`;
  if (ya === yb) return ya;
  return `’${ya.slice(2)}–’${yb.slice(2)}`;
};

